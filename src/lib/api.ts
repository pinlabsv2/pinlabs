// Typed client for the backend endpoints (POST /api/<name>).
import type { Endpoints } from '../../server/registry';
import type { z } from 'zod';

type EP<N extends keyof Endpoints> = Endpoints[N]['endpoint'];
type In<N extends keyof Endpoints> = z.input<EP<N>['inputSchema']>;
type Out<N extends keyof Endpoints> = Awaited<ReturnType<EP<N>['execute']>>;

export async function call<N extends keyof Endpoints>(name: N, input: In<N>): Promise<Out<N>> {
  const res = await fetch(`/api/${name}`, { method: 'POST', credentials: 'same-origin', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(input ?? {}) });
  const data = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(data?.message ?? `Request failed (${res.status})`);
  return data as Out<N>;
}

